pub fn lang(index: usize) -> &'static Lang {
    match index {
        0 | 1 => &ZH_CN,
        2 => &ZH_TW,
        3 | 4 => &EN,
        5 => &JA,
        6 => &KO,
        7 => &FR,
        8 => &DE,
        9 => &ES,
        10 => &IT,
        11 => &RU,
        12 => &PT,
        13 => &PL,
        14 => &NL,
        15 => &TR,
        16 => &UK,
        17 => &VI,
        18 => &ID,
        19 => &TH,
        20 => &HI,
        _ => &EN,
    }
}

pub fn detect() -> usize {
    detect_base() + 1
}

fn detect_base() -> usize {
    unsafe {
        let mut buf = [0u16; 85];
        let len = GetUserDefaultLocaleName(buf.as_mut_ptr(), 85);
        if len > 1 {
            let name = String::from_utf16_lossy(&buf[..(len as usize - 1)]).to_ascii_lowercase();
            if name.starts_with("zh") {
                if name.contains("tw") || name.contains("hk") || name.contains("mo") || name.contains("hant") {
                    return 1;
                }
                return 0;
            }
        }
        let id = GetUserDefaultUILanguage() as u32;
        let primary = id & 0x3FF;
        let sub = (id >> 10) & 0x3F;
        if primary == 0x04 {
            if sub == 0x01 || sub == 0x03 {
                return 1;
            }
            return 0;
        }
        match primary {
            0x09 => {
                if sub == 0x02 {
                    return 3;
                }
                2
            }
            0x11 => 4,
            0x12 => 5,
            0x0C => 6,
            0x07 => 7,
            0x0A => 8,
            0x10 => 9,
            0x19 => 10,
            0x16 => 11,
            0x15 => 12,
            0x13 => 13,
            0x1F => 14,
            0x22 => 15,
            0x2A => 16,
            0x21 => 17,
            0x1E => 18,
            0x39 => 19,
            _ => 2,
        }
    }
}
